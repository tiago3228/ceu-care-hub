-- A autorização é explícita: is_admin/tem_modulo não devem dar escrita na escala a outras contas.
create or replace function public.pode_editar_escala_marcacao(_user_id uuid, _modulo text)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select public.is_ativo(_user_id)
     and _modulo = any (array[
       'marcacao_escala_adicionar', 'marcacao_escala_editar', 'marcacao_escala_excluir'
     ]::text[])
     and exists (
       select 1 from public.usuario_permissoes
       where user_id = _user_id and modulo = _modulo
     )
$$;
revoke all on function public.pode_editar_escala_marcacao(uuid, text) from public, anon;
grant execute on function public.pode_editar_escala_marcacao(uuid, text) to authenticated;

