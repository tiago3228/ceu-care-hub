-- Salva cabeçalho e vínculos numa única transação, mantendo a autorização RLS do usuário.
create or replace function public.salvar_marcacao_escala(
  p_id bigint,
  p_data date,
  p_medico_id bigint,
  p_horario_inicio time,
  p_horario_fim time,
  p_observacoes text,
  p_colaboradora_ids bigint[] default '{}'
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_id bigint;
  v_perm text;
begin
  if auth.uid() is null or not public.tem_modulo(auth.uid(), 'marcacao_escala_visualizar') then
    raise exception 'Sem acesso à escala de Marcação';
  end if;

  v_perm := case when p_id is null then 'marcacao_escala_adicionar' else 'marcacao_escala_editar' end;
  if not public.pode_editar_escala_marcacao(auth.uid(), v_perm) then
    raise exception 'Sem permissão para salvar esta escala';
  end if;

  if p_horario_inicio is not null and p_horario_fim is not null and p_horario_fim <= p_horario_inicio then
    raise exception 'O horário final deve ser posterior ao inicial';
  end if;

  if not exists (select 1 from public.marcacao_medicos where id = p_medico_id and ativo) then
    raise exception 'Selecione um médico ativo da Marcação';
  end if;

  if exists (
    select 1
    from unnest(coalesce(p_colaboradora_ids, '{}'::bigint[])) as selecionada(id)
    left join public.marcacao_colaboradores c on c.id = selecionada.id
    where c.id is null or not c.ativo
  ) then
    raise exception 'A escala contém uma colaboradora inativa ou inexistente';
  end if;

  if p_id is null then
    insert into public.marcacao_escalas (
      data, medico_id, horario_inicio, horario_fim, observacoes, created_by, updated_by
    ) values (
      p_data, p_medico_id, p_horario_inicio, p_horario_fim, nullif(btrim(p_observacoes), ''), auth.uid(), auth.uid()
    ) returning id into v_id;
  else
    update public.marcacao_escalas
       set data = p_data,
           medico_id = p_medico_id,
           horario_inicio = p_horario_inicio,
           horario_fim = p_horario_fim,
           observacoes = nullif(btrim(p_observacoes), ''),
           updated_by = auth.uid(),
           updated_at = now()
     where id = p_id
     returning id into v_id;
    if v_id is null then raise exception 'Escala não encontrada ou sem permissão para editar'; end if;
  end if;

  delete from public.marcacao_escala_colaboradores where escala_id = v_id;
  insert into public.marcacao_escala_colaboradores (escala_id, colaboradora_id)
  select v_id, selecionada.id
  from (select distinct unnest(coalesce(p_colaboradora_ids, '{}'::bigint[])) as id) selecionada;

  return v_id;
end;
$$;
revoke all on function public.salvar_marcacao_escala(bigint, date, bigint, time, time, text, bigint[]) from public, anon;
grant execute on function public.salvar_marcacao_escala(bigint, date, bigint, time, time, text, bigint[]) to authenticated;

