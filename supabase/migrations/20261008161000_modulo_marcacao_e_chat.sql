create or replace function public.chat_marcacao_anexo_autorizado(_remetente text, _destinatario text)
returns boolean
language plpgsql stable security definer
set search_path = public, auth
as $$
declare
  v_remetente uuid;
  v_destinatario uuid;
begin
  if _remetente !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
     or _destinatario !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    return false;
  end if;
  v_remetente := _remetente::uuid;
  v_destinatario := _destinatario::uuid;
  return auth.uid() in (v_remetente, v_destinatario)
    and public.chat_marcacao_pode_conversar(v_remetente, v_destinatario);
end;
$$;
revoke all on function public.chat_marcacao_anexo_autorizado(text, text) from public, anon;
grant execute on function public.chat_marcacao_anexo_autorizado(text, text) to authenticated;

