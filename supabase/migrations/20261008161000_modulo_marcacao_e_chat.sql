-- -------------------- Chat privado e direcionado --------------------
create or replace function public.chat_marcacao_eh_coordenadora(_user_id uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select public.is_ativo(_user_id)
     and exists (
       select 1 from public.usuario_permissoes
       where user_id = _user_id and modulo = 'marcacao_coordenacao'
     )
$$;

create or replace function public.chat_marcacao_eh_colaborador(_user_id uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select public.is_ativo(_user_id)
     and not public.chat_marcacao_eh_coordenadora(_user_id)
     and (
       exists (
         select 1 from public.profiles p
         where p.id = _user_id and lower(coalesce(p.setor, '')) in ('marcação', 'marcacao')
       )
       or public.has_role(_user_id, 'marcacao'::public.app_role)
     )
$$;

create or replace function public.pode_chat_marcacao(_user_id uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select public.is_ativo(_user_id)
     and (
       public.is_master(_user_id)
       or public.is_admin(_user_id)
       or public.chat_marcacao_eh_coordenadora(_user_id)
       or public.chat_marcacao_eh_colaborador(_user_id)
       or public.chat_coordenadora_entre_setores(_user_id)
     )
$$;

create or replace function public.chat_marcacao_pode_conversar(_remetente uuid, _destinatario uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select _remetente is not null
     and _destinatario is not null
     and _remetente <> _destinatario
     and public.is_ativo(_remetente)
     and public.is_ativo(_destinatario)
     and (
       (
         public.chat_marcacao_eh_coordenadora(_remetente)
         and (
           public.chat_marcacao_eh_colaborador(_destinatario)
           or public.chat_coordenadora_entre_setores(_destinatario)
           or public.is_master(_destinatario)
           or public.is_admin(_destinatario)
         )
       )
       or
       (
         public.chat_marcacao_eh_coordenadora(_destinatario)
         and (
           public.chat_marcacao_eh_colaborador(_remetente)
           or public.chat_coordenadora_entre_setores(_remetente)
           or public.is_master(_remetente)
           or public.is_admin(_remetente)
         )
       )
     )
$$;

create or replace function public.obter_chat_marcacao_contatos()
returns table (id uuid, nome text, setor text, ativo boolean, tipo text)
language sql stable security definer
set search_path = public, auth
as $$
  select distinct p.id, p.nome, p.setor, p.ativo,
    case
      when public.chat_marcacao_eh_coordenadora(p.id) then 'Coordenadora de Marcação'
      when public.is_master(p.id) then 'Administrador Master'
      when public.is_admin(p.id) then 'Administrador'
      when public.chat_coordenadora_entre_setores(p.id) then 'Coordenação'
      else 'Colaborador de Marcação'
    end as tipo
  from public.profiles p
  join auth.users u on u.id = p.id
  where auth.uid() is not null
    and public.pode_chat_marcacao(auth.uid())
    and p.ativo = true
    and p.id <> auth.uid()
    and (
      (
        public.chat_marcacao_eh_coordenadora(auth.uid())
        and (
          public.chat_marcacao_eh_colaborador(p.id)
          or public.chat_coordenadora_entre_setores(p.id)
          or public.is_master(p.id)
          or public.is_admin(p.id)
        )
      )
      or
      (
        (
          public.chat_marcacao_eh_colaborador(auth.uid())
          or public.chat_coordenadora_entre_setores(auth.uid())
          or public.is_master(auth.uid())
          or public.is_admin(auth.uid())
        )
        and public.chat_marcacao_eh_coordenadora(p.id)
      )
    )
  order by p.nome
$$;

revoke all on function public.chat_marcacao_eh_coordenadora(uuid) from public, anon;
