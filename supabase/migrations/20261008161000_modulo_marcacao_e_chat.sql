insert into public.marcacao_medicos (
  nome, apelido, crm, especialidade_principal, especialidades, procedimentos, observacoes, ativo
)
select
  m.nome, m.apelido, m.crm, m.especialidade_principal, m.especialidades, m.procedimentos, m.observacoes, m.ativo
from public.medicos m
where m.setor = 'operacao'
  and not exists (
    select 1
    from public.marcacao_medicos mm
    where lower(mm.nome) = lower(m.nome)
      and coalesce(nullif(btrim(mm.crm), ''), '') = coalesce(nullif(btrim(m.crm), ''), '')
  );

-- -------------------- Escala semanal independente --------------------
create table if not exists public.marcacao_escalas (
  id bigint generated by default as identity primary key,
  data date not null,
  medico_id bigint not null references public.marcacao_medicos(id) on delete restrict,
  horario_inicio time,
  horario_fim time,
  observacoes text,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint marcacao_escalas_horario_valido
    check (horario_inicio is null or horario_fim is null or horario_fim > horario_inicio)
);

create index if not exists marcacao_escalas_data_idx
  on public.marcacao_escalas (data, horario_inicio, medico_id);

create table if not exists public.marcacao_escala_colaboradores (
  escala_id bigint not null references public.marcacao_escalas(id) on delete cascade,
  colaboradora_id bigint not null references public.marcacao_colaboradores(id) on delete restrict,
  primary key (escala_id, colaboradora_id)
);

create index if not exists marcacao_escala_colaboradores_pessoa_idx
  on public.marcacao_escala_colaboradores (colaboradora_id, escala_id);

