create table if not exists public.chat_marcacao_mensagens (
  id bigint generated by default as identity primary key,
  remetente_id uuid not null references auth.users(id) on delete cascade,
  destinatario_id uuid not null references auth.users(id) on delete cascade,
  mensagem text,
  criado_em timestamptz not null default now(),
  lida_em timestamptz,
  anexo_path text,
  anexo_nome text,
  anexo_tipo text,
  anexo_tamanho integer,
  constraint chat_marcacao_partes_distintas check (remetente_id <> destinatario_id),
  constraint chat_marcacao_conteudo_valido check (
    (nullif(btrim(mensagem), '') is not null and char_length(mensagem) <= 4000)
    or anexo_path is not null
  ),
  constraint chat_marcacao_anexo_valido check (
    anexo_path is null or (btrim(anexo_path) <> '' and coalesce(anexo_tamanho, 0) <= 10485760)
  )
);

