-- -------------------- Permissões padrão e perfil individual da Geise --------------------
insert into public.usuario_permissoes (user_id, modulo)
select p.id, permissao
from public.profiles p
cross join unnest(array[
  'marcacao_acessar',
  'marcacao_escala_visualizar',
  'marcacao_medicos_visualizar',
  'marcacao_colaboradores_visualizar',
  'chat_marcacao'
]::text[]) as m(permissao)
where lower(coalesce(p.setor, '')) in ('marcação', 'marcacao')
   or p.setor_id = (select id from public.setores where lower(nome) in ('marcação', 'marcacao') order by id limit 1)
on conflict (user_id, modulo) do nothing;

do $$
declare
  v_geise uuid;
  v_setor_id bigint;
begin
  select id into v_setor_id
  from public.setores
  where lower(nome) in ('marcação', 'marcacao')
  order by id
  limit 1;

  select p.id into v_geise
  from public.profiles p
  join auth.users u on u.id = p.id
  where lower(u.email) = 'marcacao@clinicaceu.com.br'
  order by p.id
  limit 1;

  delete from public.usuario_permissoes
  where modulo = any(array[
    'marcacao_escala_adicionar',
    'marcacao_escala_editar',
    'marcacao_escala_excluir',
    'marcacao_coordenacao',
    'chat_marcacao_coordenacao'
  ]::text[])
    and (v_geise is null or user_id <> v_geise);

  if v_geise is null then
    raise notice 'Conta da coordenadora de Marcação não encontrada; o perfil individual será aplicado quando ela estiver cadastrada.';
    return;
  end if;

  update public.profiles
     set nome = 'Geisiane Taise Gomes Moraes',
         setor = 'Marcação',
         setor_id = v_setor_id
   where id = v_geise;

  -- Define o perfil de coordenadora; preserva apenas um eventual Administrador Master.
  if not public.is_master(v_geise) then
    delete from public.user_roles where user_id = v_geise;
    insert into public.user_roles (user_id, role) values (v_geise, 'marcacao')
    on conflict (user_id, role) do nothing;
  end if;

  insert into public.usuario_permissoes (user_id, modulo)
  select v_geise, permissao
  from unnest(array[
    'marcacao_acessar',
    'marcacao_escala_visualizar',
    'marcacao_escala_adicionar',
    'marcacao_escala_editar',
    'marcacao_escala_excluir',
    'marcacao_medicos_visualizar',
    'marcacao_colaboradores_visualizar',
    'marcacao_coordenacao',
    'chat_marcacao',
    'chat_marcacao_coordenacao'
  ]::text[]) as m(permissao)
  on conflict (user_id, modulo) do nothing;
end;
$$;

