-- -------------------- Setor e permissões padrão --------------------
insert into public.setores as setor (nome, papel_padrao, permissoes_padrao)
values (
  'Marcação',
  'marcacao',
  array[
    'marcacao_acessar',
    'marcacao_escala_visualizar',
    'marcacao_medicos_visualizar',
    'marcacao_colaboradores_visualizar',
    'chat_marcacao'
  ]::text[]
)
on conflict (nome) do update
set papel_padrao = excluded.papel_padrao,
    permissoes_padrao = array(
  select distinct permissao
  from unnest(
    array(
      select permissao
      from unnest(coalesce(setor.permissoes_padrao, '{}'::text[])) as antigo(permissao)
      where permissao not in (
        'marcacao_escala_adicionar',
        'marcacao_escala_editar',
        'marcacao_escala_excluir',
        'marcacao_coordenacao',
        'chat_marcacao_coordenacao'
      )
    ) || excluded.permissoes_padrao
  ) as p(permissao)
  order by permissao
),
    atualizado_em = now();

