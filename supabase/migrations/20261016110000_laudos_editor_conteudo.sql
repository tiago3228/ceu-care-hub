-- Conteúdo da biblioteca de Laudos, separado por médico.
create table if not exists public.laudos_autotextos (
  id bigint generated by default as identity primary key,
  medico_id bigint not null references public.medicos(id) on delete cascade,
  nome text not null,
  abreviacao text not null,
  conteudo_html text not null,
  conteudo_texto text not null default '',
  origem_arquivo text,
  criado_por uuid references auth.users(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint laudos_autotextos_nome_nao_vazio check (length(btrim(nome)) > 0),
  constraint laudos_autotextos_abreviacao_nao_vazia check (length(btrim(abreviacao)) > 0)
);
create unique index if not exists laudos_autotextos_medico_abreviacao_idx
  on public.laudos_autotextos (medico_id, lower(btrim(abreviacao)));
create index if not exists laudos_autotextos_medico_nome_idx
  on public.laudos_autotextos (medico_id, nome);
grant select, insert, update, delete on public.laudos_autotextos to authenticated;
grant usage, select on sequence public.laudos_autotextos_id_seq to authenticated;
alter table public.laudos_autotextos enable row level security;

create table if not exists public.laudos_documentos (
  id uuid primary key default gen_random_uuid(),
  medico_id bigint not null references public.medicos(id) on delete restrict,
  titulo text not null,
  conteudo_html text not null default '',
  conteudo_texto text not null default '',
  criado_por uuid not null references auth.users(id) on delete restrict,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint laudos_documentos_titulo_nao_vazio check (length(btrim(titulo)) > 0)
);
create index if not exists laudos_documentos_medico_atualizado_idx
  on public.laudos_documentos (medico_id, atualizado_em desc);
grant select, insert, update, delete on public.laudos_documentos to authenticated;
alter table public.laudos_documentos enable row level security;

create table if not exists public.laudos_fontes (
  id uuid primary key default gen_random_uuid(),
  familia text not null unique,
  caminho_storage text not null unique,
  formato text not null default 'ttf' check (formato = 'ttf'),
  criado_por uuid not null references auth.users(id) on delete restrict,
  criado_em timestamptz not null default now()
);
grant select, insert, delete on public.laudos_fontes to authenticated;
alter table public.laudos_fontes enable row level security;

create table if not exists public.laudos_importacoes (
  id uuid primary key default gen_random_uuid(),
  medico_id bigint not null references public.medicos(id) on delete restrict,
  arquivo_nome text not null,
  formato text not null,
  status text not null check (status in ('concluida', 'parcial', 'sem_conteudo', 'formato_nao_suportado')),
  resumo text not null,
  detalhes jsonb not null default '{}'::jsonb,
  total_importados integer not null default 0 check (total_importados >= 0),
  total_nao_importados integer not null default 0 check (total_nao_importados >= 0),
  criado_por uuid not null references auth.users(id) on delete restrict,
  criado_em timestamptz not null default now()
);
create index if not exists laudos_importacoes_medico_data_idx
  on public.laudos_importacoes (medico_id, criado_em desc);
grant select, insert on public.laudos_importacoes to authenticated;
alter table public.laudos_importacoes enable row level security;

-- Uma política de leitura compartilhada limita conteúdo ao médico que está na biblioteca.
drop policy if exists laudos_autotextos_select on public.laudos_autotextos;
create policy laudos_autotextos_select on public.laudos_autotextos
  for select to authenticated
  using (
    public.tem_modulo(auth.uid(), 'salas')
    and exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_autotextos.medico_id)
  );
drop policy if exists laudos_autotextos_insert on public.laudos_autotextos;
create policy laudos_autotextos_insert on public.laudos_autotextos
  for insert to authenticated
  with check (
    public.pode_editar(auth.uid(), 'salas')
    and exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_autotextos.medico_id)
  );
drop policy if exists laudos_autotextos_update on public.laudos_autotextos;
create policy laudos_autotextos_update on public.laudos_autotextos
  for update to authenticated
  using (public.pode_editar(auth.uid(), 'salas'))
  with check (
    public.pode_editar(auth.uid(), 'salas')
    and exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_autotextos.medico_id)
  );
drop policy if exists laudos_autotextos_delete on public.laudos_autotextos;
create policy laudos_autotextos_delete on public.laudos_autotextos
  for delete to authenticated
  using (public.pode_editar(auth.uid(), 'salas'));

-- Documentos são compartilhados apenas com usuários que têm acesso à área e ao médico.
drop policy if exists laudos_documentos_select on public.laudos_documentos;
create policy laudos_documentos_select on public.laudos_documentos
  for select to authenticated
  using (
    public.tem_modulo(auth.uid(), 'salas')
    and exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_documentos.medico_id)
  );
drop policy if exists laudos_documentos_insert on public.laudos_documentos;
create policy laudos_documentos_insert on public.laudos_documentos
  for insert to authenticated
  with check (
    criado_por = auth.uid()
    and public.pode_editar(auth.uid(), 'salas')
    and exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_documentos.medico_id)
  );
drop policy if exists laudos_documentos_update on public.laudos_documentos;
create policy laudos_documentos_update on public.laudos_documentos
  for update to authenticated
  using (
    public.pode_editar(auth.uid(), 'salas')
    and (criado_por = auth.uid() or public.is_admin(auth.uid()))
  )
  with check (
    public.pode_editar(auth.uid(), 'salas')
    and exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_documentos.medico_id)
  );
drop policy if exists laudos_documentos_delete on public.laudos_documentos;
create policy laudos_documentos_delete on public.laudos_documentos
  for delete to authenticated
  using (
    public.pode_editar(auth.uid(), 'salas')
    and (criado_por = auth.uid() or public.is_admin(auth.uid()))
  );

-- Famílias de fonte customizadas podem ser lidas por usuários com acesso a Laudos.
drop policy if exists laudos_fontes_select on public.laudos_fontes;
create policy laudos_fontes_select on public.laudos_fontes
  for select to authenticated using (public.tem_modulo(auth.uid(), 'salas'));
drop policy if exists laudos_fontes_insert on public.laudos_fontes;
create policy laudos_fontes_insert on public.laudos_fontes
  for insert to authenticated
  with check (
    public.pode_gerenciar_medicos_laudos(auth.uid())
    and criado_por = auth.uid()
  );
drop policy if exists laudos_fontes_delete on public.laudos_fontes;
create policy laudos_fontes_delete on public.laudos_fontes
  for delete to authenticated
  using (public.pode_gerenciar_medicos_laudos(auth.uid()));

