-- Somente a Marilia Frontzek é retornada como coordenadora das Salas.
create or replace function public.obter_chat_salas_coordenadora()
returns table (id uuid, nome text, setor text, ativo boolean)
language sql stable security definer set search_path = public, auth as $$
  select p.id, p.nome, p.setor, p.ativo
  from public.profiles p join auth.users u on u.id = p.id
  where p.ativo = true
    and (lower(trim(p.nome)) = 'marilia frontzek' or lower(u.email) in ('supervisaosalas@clinicaceu.com.br', 'supervisaosalas@clinicacue.com.br'))
  order by (lower(trim(p.nome)) = 'marilia frontzek') desc,
           (lower(u.email) = 'supervisaosalas@clinicacue.com.br') desc
  limit 1
$$;
grant execute on function public.obter_chat_salas_coordenadora() to authenticated;
