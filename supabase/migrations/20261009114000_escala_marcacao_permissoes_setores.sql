create or replace function public.pode_chat_marcacao(_user_id uuid)
returns boolean language sql stable security definer set search_path = public, auth as $$
  select public.is_ativo(_user_id) and (
    public.is_admin(_user_id)
    or exists (select 1 from public.usuario_permissoes where user_id = _user_id and modulo = 'chat_marcacao')
    or exists (select 1 from auth.users where id = _user_id and lower(email) = 'marcacao@clinicaceu.com.br')
  )
$$;
create or replace function public.chat_marcacao_eh_supervisora(_user_id uuid)
returns boolean language sql stable security definer set search_path = public, auth as $$
  select public.pode_chat_marcacao(_user_id) and exists (
    select 1 from auth.users u join public.profiles p on p.id = u.id
    where u.id = _user_id and (lower(u.email) = 'marcacao@clinicaceu.com.br' or lower(trim(p.nome)) = 'geisiane taise gomes moraes')
  )
$$;
create or replace function public.obter_chat_marcacao_supervisora()
returns table (id uuid, nome text, setor text, ativo boolean)
language sql stable security definer set search_path = public, auth as $$
  select p.id, p.nome, p.setor, p.ativo
  from public.profiles p join auth.users u on u.id = p.id
  where p.ativo = true and (lower(u.email) = 'marcacao@clinicaceu.com.br' or lower(trim(p.nome)) = 'geisiane taise gomes moraes')
  order by (lower(u.email) = 'marcacao@clinicaceu.com.br') desc
  limit 1
$$;
