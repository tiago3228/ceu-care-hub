-- Escalas independentes por setor: Salas, Enfermagem e Marcação.
-- A nova tela da Marcação possui tabela própria e permissões independentes.

create table if not exists public.escalas_marcacao (
  id bigint generated by default as identity primary key,
  data date not null,
  periodo text,
  responsaveis text,
  observacoes text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);
create index if not exists escalas_marcacao_data_idx on public.escalas_marcacao (data);
drop trigger if exists trg_escalas_marcacao_touch on public.escalas_marcacao;
create trigger trg_escalas_marcacao_touch before update on public.escalas_marcacao
for each row execute function public.touch_updated_at();
grant select, insert, update, delete on public.escalas_marcacao to authenticated;
grant all on public.escalas_marcacao to service_role;
grant usage, select on sequence public.escalas_marcacao_id_seq to authenticated;
alter table public.escalas_marcacao enable row level security;
drop policy if exists escalas_marcacao_select on public.escalas_marcacao;
drop policy if exists escalas_marcacao_insert on public.escalas_marcacao;
drop policy if exists escalas_marcacao_update on public.escalas_marcacao;
drop policy if exists escalas_marcacao_delete on public.escalas_marcacao;
create policy escalas_marcacao_select on public.escalas_marcacao for select to authenticated
using (public.tem_modulo(auth.uid(), 'escala_marcacao_visualizar') or public.tem_modulo(auth.uid(), 'escala_marcacao_editar'));
create policy escalas_marcacao_insert on public.escalas_marcacao for insert to authenticated
with check (public.pode_editar(auth.uid(), 'escala_marcacao_editar'));
create policy escalas_marcacao_update on public.escalas_marcacao for update to authenticated
using (public.pode_editar(auth.uid(), 'escala_marcacao_editar'))
with check (public.pode_editar(auth.uid(), 'escala_marcacao_editar'));
create policy escalas_marcacao_delete on public.escalas_marcacao for delete to authenticated
using (public.pode_editar(auth.uid(), 'escala_marcacao_editar'));

-- Catálogo de permissões e migração das permissões antigas da escala de Salas.
update public.setores
set permissoes_padrao = array(
  select distinct permissao from unnest(permissoes_padrao || array['escala_salas_visualizar','escala_salas_editar']::text[]) p(permissao)
  order by permissao
), atualizado_em = now()
where papel_padrao in ('admin_master'::public.app_role, 'administrador'::public.app_role);
update public.setores
set permissoes_padrao = array(
  select distinct permissao from unnest(permissoes_padrao || array['escala_marcacao_visualizar','escala_marcacao_editar']::text[]) p(permissao)
  order by permissao
), atualizado_em = now()
where lower(replace(nome, 'ã', 'a')) = 'marcacao' or papel_padrao = 'marcacao'::public.app_role;
insert into public.usuario_permissoes (user_id, modulo)
select distinct up.user_id, 'escala_salas_visualizar'
from public.usuario_permissoes up
where up.modulo in ('escalas', 'escalas_visualizar', 'escalas_editar')
on conflict (user_id, modulo) do nothing;
insert into public.usuario_permissoes (user_id, modulo)
select distinct up.user_id, 'escala_salas_editar'
from public.usuario_permissoes up
where up.modulo in ('escalas', 'escalas_editar')
on conflict (user_id, modulo) do nothing;
insert into public.usuario_permissoes (user_id, modulo)
select p.id, permissao
from public.profiles p
join public.setores s on s.id = p.setor_id
cross join unnest(array['escala_marcacao_visualizar','escala_marcacao_editar']::text[]) permissao
where lower(replace(coalesce(s.nome, ''), 'ã', 'a')) = 'marcacao' or s.papel_padrao = 'marcacao'::public.app_role
on conflict (user_id, modulo) do nothing;

