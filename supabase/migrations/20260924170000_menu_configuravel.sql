-- Permite que administradores personalizem os textos e botões do menu principal.
create table if not exists public.menu_itens (
  id bigint generated by default as identity primary key,
  chave text not null unique,
  grupo text not null default 'Geral',
  grupo_ordem integer not null default 100,
  rotulo varchar(120) not null,
  destino varchar(255) not null,
  icone varchar(40) not null default 'LayoutDashboard',
  modulo varchar(80),
  ordem integer not null default 100,
  ativo boolean not null default true,
  somente_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint menu_itens_rotulo_nao_vazio check (btrim(rotulo) <> ''),
  constraint menu_itens_destino_nao_vazio check (btrim(destino) <> ''),
  constraint menu_itens_ordem_valida check (ordem >= 0 and grupo_ordem >= 0)
);

comment on table public.menu_itens is
  'Itens do menu principal que podem ser personalizados por administradores.';

create index if not exists menu_itens_visiveis_idx
  on public.menu_itens (ativo, grupo_ordem, ordem);

