alter table public.menu_itens enable row level security;

drop policy if exists menu_itens_select on public.menu_itens;
create policy menu_itens_select
  on public.menu_itens for select to authenticated
  using (public.is_ativo(auth.uid()));

drop policy if exists menu_itens_admin on public.menu_itens;
create policy menu_itens_admin
  on public.menu_itens for all to authenticated
  using (public.is_admin(auth.uid()))
  with check (public.is_admin(auth.uid()));
