insert into public.usuario_permissoes (user_id, modulo)
select p.id, 'agendamento_marcacao_automacao'
from public.profiles p
where p.ativo = true
  and lower(replace(replace(coalesce(p.setor, ''), 'ã', 'a'), 'ç', 'c')) = 'marcacao'
on conflict (user_id, modulo) do nothing;

insert into public.usuario_permissoes (user_id, modulo)
select p.id, 'agendamento_marcacao_automacao'
from public.profiles p
where p.ativo = true
  and exists (select 1 from public.user_roles ur where ur.user_id = p.id and ur.role in ('admin_master'::public.app_role, 'administrador'::public.app_role))
on conflict (user_id, modulo) do nothing;
