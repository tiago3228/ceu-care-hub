-- Materiais recebidos para a biblioteca de Laudos.
-- medico_id nulo representa a pasta virtual "Outros".
create table if not exists public.laudos_materiais (
  id bigint generated by default as identity primary key,
  medico_id bigint references public.medicos(id) on delete cascade,
  categoria text not null check (categoria in ('ajuda', 'atestado', 'outros')),
  titulo text not null,
  conteudo_texto text not null default '',
  origem_arquivo text,
  caminho_origem text,
  ordem integer not null default 0,
  criado_por uuid references auth.users(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint laudos_materiais_titulo_nao_vazio check (length(btrim(titulo)) > 0)
);

create index if not exists laudos_materiais_medico_categoria_idx
  on public.laudos_materiais (medico_id, categoria, ordem, titulo);
create index if not exists laudos_materiais_busca_idx
  on public.laudos_materiais using gin (to_tsvector('portuguese', titulo || ' ' || conteudo_texto));

grant select, insert, update, delete on public.laudos_materiais to authenticated;
grant usage, select on sequence public.laudos_materiais_id_seq to authenticated;
alter table public.laudos_materiais enable row level security;

drop policy if exists laudos_materiais_select on public.laudos_materiais;
create policy laudos_materiais_select on public.laudos_materiais
  for select to authenticated
  using (
    public.tem_modulo(auth.uid(), 'salas')
    and (
      medico_id is null
      or exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_materiais.medico_id)
    )
  );

drop policy if exists laudos_materiais_insert on public.laudos_materiais;
create policy laudos_materiais_insert on public.laudos_materiais
  for insert to authenticated
  with check (
    public.pode_editar(auth.uid(), 'salas')
    and (
      medico_id is null
      or exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_materiais.medico_id)
    )
  );

drop policy if exists laudos_materiais_update on public.laudos_materiais;
create policy laudos_materiais_update on public.laudos_materiais
  for update to authenticated
  using (public.pode_editar(auth.uid(), 'salas'))
  with check (
    public.pode_editar(auth.uid(), 'salas')
    and (
      medico_id is null
      or exists (select 1 from public.laudos_medicos lm where lm.medico_id = laudos_materiais.medico_id)
    )
  );

drop policy if exists laudos_materiais_delete on public.laudos_materiais;
create policy laudos_materiais_delete on public.laudos_materiais
  for delete to authenticated
  using (public.pode_editar(auth.uid(), 'salas'));
